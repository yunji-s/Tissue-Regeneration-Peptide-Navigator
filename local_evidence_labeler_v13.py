def batch_status(before, after):
    """Classify one attempt without asserting that the LLM succeeded on a skip."""
    if after is None:
        return "NO_SUMMARY"
    if (before is not None and before["source_hash"] == after["source_hash"]
            and before["created_at"] == after["created_at"]):
        return "ALREADY_SAVED"
    return "SAVED"


def run_all(db, args):
    """Process existing Screening DB only, with per-record checkpoint and report."""
    rows = list(db.execute("SELECT * FROM excel_screening ORDER BY record_id"))
    if not rows:
        raise RuntimeError("No Screening records found in excel_screening")
    eligible = [r for r in rows if doi_normalize(r["doi"])]
    missing = [r for r in rows if not doi_normalize(r["doi"])]
    unique_dois = {doi_normalize(r["doi"]) for r in eligible}
    print(f"Full-DB coverage: {len(rows)} records | {len(eligible)} with DOI | "
          f"{len(missing)} without DOI | {len(unique_dois)} unique DOIs", flush=True)
    print("Existing Screening DB is read-only. All outputs require manual review.", flush=True)
    if args.all_preview:
        for r in rows:
            print(f"  {r['record_id']:7} | {str(r['peptide']):10} | "
                  f"{doi_normalize(r['doi']) or 'NO_DOI'}")
        print("PREVIEW ONLY: no DOI requests or Ollama calls performed.")
        return

    # Keep existing ordering by record_id for predictable resuming and reports.
    # The DOI source cache means repeated DOI records never require repeated retrieval.
    if args.limit:
        eligible = eligible[:args.limit]
    report_path = ROOT / "all_records_results.json"
    report = {
        "generated_at": now(), "model": args.model,
        "records_in_screening": len(rows), "records_with_doi": len(rows) - len(missing),
        "records_without_doi": len(missing), "unique_dois": len(unique_dois),
        "forced": bool(args.force), "limit": args.limit,
        "status": "RUNNING", "attempted": 0,
        "results": [
            {"record_id": r["record_id"], "peptide": r["peptide"],
             "doi": "", "status": "NO_DOI", "note": "Original record preserved"}
            for r in missing
        ],
    }

    def checkpoint():
        report["updated_at"] = now()
        # Atomic JSON replacement so interruption does not corrupt previous checkpoints.
        temp_path = report_path.with_suffix(".json.tmp")
        temp_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8-sig")
        temp_path.replace(report_path)

    checkpoint()
    interrupted = False
    try:
        for i, r in enumerate(eligible, 1):
            rid = r["record_id"]
            doi = doi_normalize(r["doi"])
            print(f"\n{'='*10} ALL {i}/{len(eligible)} | {rid} | {doi} {'='*10}", flush=True)
            previous = db.execute("SELECT source_hash,created_at FROM qualitative_summaries_v2 WHERE record_id=?", (rid,)).fetchone()
            item = {"record_id": rid, "peptide": r["peptide"], "doi": doi}
            try:
                run_record(db, r, args)
                after = db.execute("SELECT source_hash,created_at,verification_status,summary_ko,evidence_type,certainty_check FROM qualitative_summaries_v2 WHERE record_id=?", (rid,)).fetchone()
                item["status"] = batch_status(previous, after)
                if after:
                    item.update(verification_status=after["verification_status"],
                                summary_en=after["summary_ko"],
                                evidence_type=after["evidence_type"],
                                certainty_check=after["certainty_check"])
            except KeyboardInterrupt:
                interrupted = True
                print("Interrupted: completed summaries and report checkpoint retained.", flush=True)
                break
            except Exception as e:
                item["status"] = "ERROR"
                item["error"] = f"{type(e).__name__}: {e}"
                print(f"BATCH ERROR [{rid}]: {item['error']}", flush=True)
            report["results"].append(item)
            report["attempted"] += 1
            checkpoint()
    finally:
        report["status"] = "INTERRUPTED" if interrupted else "COMPLETE"
        counts = {}
        for item in report["results"]:
            counts[item["status"]] = counts.get(item["status"], 0) + 1
        report["status_counts"] = counts
        checkpoint()
        print("\nFULL-DB SUMMARY:", flush=True)
        for status, count in sorted(counts.items()):
            print(f"  {status}: {count}", flush=True)
        print(f"  Attempted in this run: {report['attempted']} / {len(eligible)}", flush=True)
        print(f"  Report: {report_path}", flush=True)
        print("  Previously saved results are retained; rerun without --force to resume.", flush=True)


def main():
    parser = argparse.ArgumentParser(description="Existing-DOI, abstract-first qualitative summarizer")
    parser.add_argument("--db", type=Path, default=ROOT / "navigator.sqlite3")
    parser.add_argument("--model", default=MODEL)
    parser.add_argument("--record-id")
    parser.add_argument("--pilot-five", action="store_true", help="Run five distinct DOI records across five peptide families")
    parser.add_argument("--all-records", action="store_true", help="Summarize all existing Screening records with DOIs; resumable")
    parser.add_argument("--all-preview", action="store_true", help="Print full-DB coverage and DOI counts without network/LLM calls")
    parser.add_argument("--limit", type=int, default=0, help="Optional limit on eligible records for a small batch test (0=all)")
    parser.add_argument("--pilot-preview", action="store_true", help="Show five pilot records without network/model calls")
    parser.add_argument("--list", action="store_true")
    parser.add_argument("--fetch-only", action="store_true")
    parser.add_argument("--allow-abstract", action="store_true")
    parser.add_argument("--refresh-source", action="store_true")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--timeout", type=int, default=180)
    parser.add_argument("--max-tokens", type=int, default=320)
    parser.add_argument("--max-abstract-chars", type=int, default=1400)
    parser.add_argument("--debug-llm", action="store_true")
    parser.add_argument("--inspect-evidence", action="store_true", help="Show ranked abstract evidence sentences without calling Ollama")
    parser.add_argument("--allow-other-outcome", action="store_true", help="Permit a different endpoint when the exact DB endpoint is absent")
    parser.add_argument("--max-sentence-chars", type=int, default=520)
    parser.add_argument("--report", action="store_true")
    parser.add_argument("--export-json", type=Path)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return
    if args.timeout < 5 or args.max_tokens < 50 or args.max_sentence_chars < 120 or args.limit < 0:
        parser.error("Timeout/max-tokens/max-sentence-chars out of range")
    if not args.db.is_file():
        parser.error(f"DB not found: {args.db}")
    db = open_db(args.db)
    try:
        if args.all_records or args.all_preview:
            run_all(db, args)
        elif args.pilot_five or args.pilot_preview:
            run_pilot(db, args)
        elif args.list:
            for row in db.execute("SELECT record_id,peptide,doi FROM excel_screening ORDER BY record_id"):
                info = db.execute("SELECT source_kind FROM doi_source_cache_v1 WHERE doi=?", (doi_normalize(row["doi"]),)).fetchone()
                print(f"{row['record_id']:7} {row['peptide']:10} {row['doi']:47} cached={info[0] if info else 'not_fetched'}")
        elif args.report:
            for row in db.execute("SELECT source_kind,COUNT(*) FROM doi_source_cache_v1 GROUP BY source_kind"):
                print("DOI source:", *row)
            for row in db.execute("SELECT verification_status,COUNT(*) FROM qualitative_summaries_v2 GROUP BY verification_status"):
                print("summary:", *row)
        elif args.export_json:
            rows = [dict(row) for row in db.execute("SELECT * FROM qualitative_summaries_v2 ORDER BY record_id")]
            args.export_json.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8-sig")
            print(f"Exported {len(rows)} rows to {args.export_json}")
        else:
            if not args.record_id:
                parser.error("Use --all-records, --all-preview, --pilot-five, --record-id S3-018, --list, --report, or --export-json")
            row = db.execute("SELECT * FROM excel_screening WHERE record_id=?", (args.record_id,)).fetchone()
            if row is None:
                parser.error("Unknown Screening record ID")
            run_record(db, row, args)
    finally:
        db.close()


if __name__ == "__main__":
    main()
